#!/usr/bin/env python3
"""B1 (2026-08-27): resolves, does not caveat, Fast-DetectGPT's
paraphrase-attack recall anomaly (48.2%->63-86% under Gemma-2B-attacked
paraphrase_heavy, unexplained -- flagged open at P4 task5 close). Hypothesis:
Fast-DetectGPT measures curvature of log-probability; the attacks were
generated BY Gemma-2B; paraphrasing with model M produces text M finds
maximally predictable -- exactly Fast-DetectGPT's signal -- so the "attack"
raises the detector's own key metric when attacker==scorer family. Test:
regenerate paraphrase_heavy on ~2,000 docs with two attacker families that
share NEITHER Gemma's nor Fast-DetectGPT's own lineage (Qwen2.5-7B-Instruct,
Phi-3.5-mini-instruct -- both already on disk from the 24-doc bench probe),
re-score with the SAME Fast-DetectGPT (Gemma-2B curvature) pipeline used for
the whole battery.

Pre-registered (before running): if recall does NOT rise above the 51.0%/
64.8% pre-attack baseline (or rises far less than Gemma-attacked's 63.4%/
78.1%) -> mechanism confirmed, anomaly closed. If recall still rises to a
comparable or greater degree -> the same-family hypothesis is wrong and this
is a genuinely novel finding.

Real chat template (apply_chat_template), matching the 24-doc bench probe's
approach for instruction-tuned models, NOT build_edits.py's base-model
completion prompt -- these are instruct models, not gemma-2b-base.
"""
from fractalsig import paths as _paths  # noqa: E402
import argparse
import gc
import json
import os
import re
import sys

import numpy as np
import torch
from sentence_transformers import SentenceTransformer
from transformers import AutoModelForCausalLM, AutoTokenizer

HERE = _paths.WORKSPACE_STR
D = lambda *p: os.path.join(HERE, "data", *p)

from fractalsig.robustness.build_edits import trim_to_clip, CLIP_TO, MIN_TOKENS  # noqa: E402

ATTACKERS = [
    ("Qwen2.5-7B-Instruct", "Qwen/Qwen2.5-7B-Instruct"),
    ("Phi-3.5-mini-instruct", "microsoft/Phi-3.5-mini-instruct"),
]

# same task content as build_edits.py's paraphrase_heavy PROMPTS entry,
# reworded for chat-instruction format (matches p4_bench_probe_24doc.py's
# pattern: light copy-edit -> paraphrase_heavy's "thorough rewrite" content)
INSTRUCTION = ("Thoroughly rewrite the following text using different sentence "
               "structures and vocabulary throughout, while preserving its exact "
               "meaning and approximate length. Output ONLY the rewritten passage, "
               "nothing else.\n\nOriginal passage:\n{snippet}")
MAX_NEW_TOKENS = 460
N_SAMPLE = 2000
SEED = 20260827

NUMBERED_LINE_RE = re.compile(r"^\s*\(?(\d{1,2})[\.\)]\s+", re.MULTILINE)
LABEL_ARTIFACT_RE = re.compile(
    r"\b(Paraphrase[d]?|Rewrite|Rewritten passage|Original passage)\s*:", re.IGNORECASE)


def extract_numbered_items(text):
    matches = list(NUMBERED_LINE_RE.finditer(text))
    if len(matches) < 3:
        return None
    items = []
    for i, m in enumerate(matches):
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
        item_text = text[start:end].strip()
        if item_text:
            items.append(item_text)
    return items if len(items) >= 3 else None


def generate_for_model(name, model_id, docs, device, batch_size=8):
    print(f"\n[b1] === generating with {name} ===", flush=True)
    tok = AutoTokenizer.from_pretrained(model_id)
    if tok.pad_token_id is None:
        tok.pad_token_id = tok.eos_token_id
    tok.padding_side = "left"
    model = AutoModelForCausalLM.from_pretrained(model_id, dtype=torch.bfloat16).to(device).eval()

    results = []
    for i in range(0, len(docs), batch_size):
        batch = docs[i:i + batch_size]
        snippets = []
        for d in batch:
            snippet, ntok = trim_to_clip(tok, d["text"], CLIP_TO)
            snippets.append(snippet)
        prompts = [tok.apply_chat_template(
            [{"role": "user", "content": INSTRUCTION.format(snippet=s)}],
            tokenize=False, add_generation_prompt=True) for s in snippets]
        enc = tok(prompts, return_tensors="pt", padding=True, truncation=True, max_length=1024).to(device)
        with torch.no_grad():
            out = model.generate(**enc, max_new_tokens=MAX_NEW_TOKENS, do_sample=False,
                                  no_repeat_ngram_size=5, pad_token_id=tok.pad_token_id)
        for j, d in enumerate(batch):
            new_tokens = out[j][enc["input_ids"].shape[1]:]
            gen_text = tok.decode(new_tokens, skip_special_tokens=True).strip()
            results.append({"id": d["id"], "domain": d["domain"], "generator": d["generator"],
                             "attacker": name, "snippet": snippets[j], "text": gen_text})
        if (i + batch_size) % 200 == 0:
            print(f"[b1]   {i + batch_size}/{len(docs)}", flush=True)

    del model, tok
    gc.collect()
    torch.cuda.empty_cache()
    return results


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=None)
    args = ap.parse_args()

    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"[b1] device={device}", flush=True)
    if device != "cuda":
        print("[b1] WARNING: no GPU visible, this will be very slow", flush=True)

    sample = [json.loads(l) for l in open(D("p4_sampled_docs.jsonl"))]
    rng = np.random.RandomState(SEED)
    idx = rng.choice(len(sample), size=(args.limit or N_SAMPLE), replace=False)
    docs = [sample[i] for i in idx]
    print(f"[b1] {len(docs)} docs sampled (seed={SEED})", flush=True)

    all_results = []
    for name, model_id in ATTACKERS:
        results = generate_for_model(name, model_id, docs, device)
        all_results.extend(results)

    with open(D("p4_b1_cross_attacker_generations.jsonl"), "w") as f:
        for r in all_results:
            f.write(json.dumps(r) + "\n")
    print(f"\n[b1] wrote {len(all_results)} generations to data/p4_b1_cross_attacker_generations.jsonl", flush=True)

    # --- quality checks: cosine, below-min, label artifacts, B0 enumerated-list ---
    print("\n[b1] === quality checks ===", flush=True)
    embedder = SentenceTransformer("sentence-transformers/all-MiniLM-L6-v2", device=device)
    from fractalsig.pipeline.build_p1_feature_store_gpu import load_models, compute_align_window
    torch_mod, _, _, tokenizers, models, _ = load_models(scorers=("gemma-2b",))
    gemma_tok = tokenizers["gemma-2b"]

    by_attacker = {}
    for name, _ in ATTACKERS:
        rows = [r for r in all_results if r["attacker"] == name]
        snippets = [r["snippet"] for r in rows]
        texts = [r["text"] for r in rows]

        orig_emb = embedder.encode(snippets, convert_to_numpy=True, show_progress_bar=False, batch_size=64)
        gen_emb = embedder.encode(texts, convert_to_numpy=True, show_progress_bar=False, batch_size=64)
        cos = (orig_emb * gen_emb).sum(axis=1) / (
            np.linalg.norm(orig_emb, axis=1) * np.linalg.norm(gen_emb, axis=1) + 1e-8)

        below_min = 0
        for r in rows:
            ids = gemma_tok(r["text"], truncation=False)["input_ids"]
            if compute_align_window(len(ids)) is None:
                below_min += 1

        label_artifact = sum(1 for t in texts if LABEL_ARTIFACT_RE.search(t))

        enum_flagged, enum_degenerate = 0, 0
        for t in texts:
            items = extract_numbered_items(t)
            if items is not None:
                enum_flagged += 1
                emb = embedder.encode(items, convert_to_numpy=True, show_progress_bar=False)
                norm = emb / (np.linalg.norm(emb, axis=1, keepdims=True) + 1e-8)
                sim = norm @ norm.T
                n = len(items)
                iu = np.triu_indices(n, k=1)
                if float(sim[iu].mean()) >= 0.80:
                    enum_degenerate += 1

        by_attacker[name] = {
            "n": len(rows),
            "median_cosine": float(np.median(cos)),
            "frac_near_identity_cos_gt_0.98": float(np.mean(cos > 0.98)),
            "frac_low_cosine_lt_0.5": float(np.mean(cos < 0.5)),
            "below_min_tokens_rate": below_min / len(rows),
            "label_artifact_rate": label_artifact / len(rows),
            "enum_flagged": enum_flagged,
            "enum_degenerate": enum_degenerate,
            "enum_degenerate_rate": enum_degenerate / len(rows),
        }
        print(f"\n[b1] {name}:")
        for k, v in by_attacker[name].items():
            print(f"[b1]   {k}: {v}")

    # gemma-2b baseline for comparison, from the canonical corpus (same variant, same doc pool)
    gemma_edits = {}
    for path in ("p4_edits_batch1.jsonl", "p4_edits_batch2.jsonl"):
        for l in open(D(path)):
            r = json.loads(l)
            v = r["variants"].get("paraphrase_heavy")
            if v is not None and v.get("text"):
                gemma_edits[r["id"]] = v["text"]
    sample_ids = {d["id"] for d in docs}
    gemma_texts_this_sample = [gemma_edits[i] for i in sample_ids if i in gemma_edits]
    print(f"\n[b1] gemma-2b baseline available for {len(gemma_texts_this_sample)}/{len(docs)} of this sample "
          f"(for reference; full gemma-2b paraphrase_heavy stats are in the task5 ledger entry)", flush=True)

    with open(D("p4_b1_quality_summary.json"), "w") as f:
        json.dump({"n_sample": len(docs), "seed": SEED, "by_attacker": by_attacker}, f, indent=2)

    # --- Fast-DetectGPT scoring ---
    print("\n[b1] === Fast-DetectGPT scoring ===", flush=True)
    from fractalsig.baselines.fast_detectgpt_score import score_documents
    fdg_thr = json.load(open(D("p4_task5_fastdetectgpt_summary.json")))["thresholds"]
    t1, t5 = fdg_thr["t1"], fdg_thr["t5"]

    fdg_results = {}
    for name, _ in ATTACKERS:
        rows = [r for r in all_results if r["attacker"] == name]
        scores = score_documents(torch_mod, models["gemma-2b"], gemma_tok, device, rows)
        n = len(scores)
        d_vals = np.array([scores[i]["d"] for i in scores])
        r1 = float(np.mean(d_vals >= t1))
        r5 = float(np.mean(d_vals >= t5))
        fdg_results[name] = {"n_scored": n, "recall_at_1pct_fpr": r1, "recall_at_5pct_fpr": r5}
        print(f"[b1] {name}: n_scored={n} recall@1%FPR={r1:.4f} recall@5%FPR={r5:.4f}", flush=True)

    print(f"\n[b1] REFERENCE -- Fast-DetectGPT pre-attack baseline: 51.04%/64.82%", flush=True)
    print(f"[b1] REFERENCE -- Fast-DetectGPT gemma-2b-attacked paraphrase_heavy: 63.44%/78.12%", flush=True)

    verdict = "UNDETERMINED"
    both_at_or_below_baseline = all(fdg_results[n]["recall_at_1pct_fpr"] <= 0.55 for n, _ in ATTACKERS)
    both_far_below_gemma = all(fdg_results[n]["recall_at_1pct_fpr"] < 0.63 - 0.10 for n, _ in ATTACKERS)
    if both_at_or_below_baseline or both_far_below_gemma:
        verdict = "MECHANISM CONFIRMED -- recall does not rise (or rises far less) with different-family attackers"
    else:
        verdict = "MECHANISM NOT CONFIRMED -- recall still rises comparably, genuinely novel finding, needs follow-up"
    print(f"\n[b1] VERDICT: {verdict}", flush=True)

    with open(D("p4_b1_fastdetectgpt_results.json"), "w") as f:
        json.dump({"fdg_results": fdg_results, "verdict": verdict,
                    "reference_pre_attack": {"recall_at_1pct_fpr": 0.5104, "recall_at_5pct_fpr": 0.6482},
                    "reference_gemma_attacked_paraphrase_heavy": {"recall_at_1pct_fpr": 0.6344, "recall_at_5pct_fpr": 0.7812}},
                   f, indent=2)
    print("\nwritten to data/p4_b1_fastdetectgpt_results.json")


if __name__ == "__main__":
    main()
